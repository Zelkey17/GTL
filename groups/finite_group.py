from __future__ import annotations

from abc import ABC, abstractmethod
from collections.abc import Iterator

from groups.base import Group


class FiniteGroup[T, E](Group[T, E], ABC):
    """
    Абстрактный базовый класс для конечных групп.

    Этот класс задаёт общий интерфейс для конечных групп:
      - теоретико-групповые проверки (Лагранжева теорема, абелева, простая, разрешимая),
      - структурные операции (коммутант, центр),
      - итерация и доступ к элементам.

    Подклассы должны реализовать все @abstractmethod-методы.
    """

    @abstractmethod
    def is_lagrangian(self) -> bool:
        """
        Проверяет обратную теорему Лагранжа.

        Группа называется «лагранжевой», если для каждого делителя её порядка
        существует хотя бы одна подгруппа этого порядка.

        Returns:
            bool: True, если для каждого делителя порядка группы
                  найдена подгруппа соответствующего порядка.
        """

    @abstractmethod
    def is_abelian(self) -> bool:
        """
        Проверяет, является ли группа абелевой (коммутативной).

        Returns:
            bool: True, если для любых a, b ∈ G выполняется a * b == b * a.
        """

    @abstractmethod
    def is_simple(self) -> bool:
        """
        Проверяет, является ли группа простой.

        Простая группа — это группа без нетривиальных нормальных подгрупп
        (только {e} и саму группу).

        Returns:
            bool: True, если нет нормальных подгрупп кроме тривиальных.
        """

    @abstractmethod
    def is_solvable(self) -> bool:
        """
        Проверяет, является ли группа разрешимой.

        Разрешимая группа имеет составной ряд, в котором все фактор-группы абелевы,
        эквивалентно производный ряд достигает тривиальной подгруппы.

        Returns:
            bool: True, если группа разрешима.
        """

    @abstractmethod
    def __len__(self) -> int:
        """
        Возвращает порядок группы (количество элементов).

        Returns:
            int: Порядок (число элементов) конечной группы.
        """

    @abstractmethod
    def comutator(self) -> SubGroup[T, E]:
        """
        Вычисляет коммутант группы.

        Коммутант — подгруппа, порождённая всеми коммутаторами [a, b] = a * b * a⁻¹ * b⁻¹.

        Returns:
            SubGroup[T, E]: Коммутант данной группы.
        """

    @abstractmethod
    def center(self) -> SubGroup[T, E]:
        """
        Вычисляет центр группы.

        Центр — множество всех элементов, коммутирующих с любым элементом группы.

        Returns:
            SubGroup[T, E]: Центр группы.
        """

    @abstractmethod
    def __getitem__(self, item: T) -> E:
        """
        Доступ к элементу по его значению.

        Args:
            item (T): Внутреннее представление элемента.

        Returns:
            E: Соответствующий элемент группы.

        Raises:
            KeyError: Если элемент с таким значением не найден.
        """

    @abstractmethod
    def __contains__(self, item: E) -> bool:
        """
        Проверяет, принадлежит ли элемент группе.

        Args:
            item (E): Элемент для проверки.

        Returns:
            bool: True, если item принадлежит этой группе.
        """

    @abstractmethod
    def __iter__(self) -> Iterator[E]:
        """
        Итератор по всем элементам группы.

        Returns:
            Iterator[E]: Итератор для перебора элементов группы.
        """
